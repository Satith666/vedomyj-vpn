# Длинные фразы заменяем раньше коротких: иначе «Автонастройка» испортит предложение, где это слово — часть.
_COMPILED = [(re.compile(p), r) for p, r in sorted(RULES, key=lambda pr: -len(pr[0]))]
CYRILLIC = re.compile("[А-Яа-яЁё]")


def tr(text) -> str:
    """Переводит сообщение, если выбран английский. Имена серверов и сообщения провайдера остаются как есть."""
    if _lang != "en" or not text or not isinstance(text, str):
        return text
    out = []
    for line in text.split("\n"):
        for rx, repl in _COMPILED:
            line = rx.sub(repl, line)
        out.append(line)
    return "\n".join(out)


def untranslated(text: str, keep: tuple[str, ...] = ()) -> bool:
    """Остались ли русские буквы после перевода (без учёта имён из keep)."""
    t = tr(text)
    for k in keep:
        t = t.replace(k, "")
    return bool(CYRILLIC.search(t))
